        public static Texture2D CreateCenteredText(string text)
        {
            string[] lines = text.Replace("\r", "").ToUpperInvariant().Split('\n');
            int width = 1;
            foreach (string line in lines)
                width = Mathf.Max(width, LineWidth(line));
            int height = lines.Length * (GlyphHeight + LineSpacing) - LineSpacing;
            var pixels = new Color32[width * height];
            var ink = new Color32(255, 255, 255, 255);

            for (int lineIndex = 0; lineIndex < lines.Length; lineIndex++)
            {
                string line = lines[lineIndex];
                int left = (width - LineWidth(line)) / 2;
                for (int character = 0; character < line.Length; character++)
                {
                    if (line[character] == ' ')
                        continue;
                    if (!Glyphs.TryGetValue(line[character], out string glyph))
                        glyph = Glyphs['?'];

                    for (int row = 0; row < GlyphHeight; row++)
                        for (int column = 0; column < GlyphWidth; column++)
                        {
                            if (glyph[row * (GlyphWidth + 1) + column] != '#')
                                continue;
                            int x = left + character * (GlyphWidth + LetterSpacing) + column;
                            int y = height - 1 - lineIndex * (GlyphHeight + LineSpacing) - row;
                            pixels[y * width + x] = ink;
                        }
                }
            }

            var texture = new Texture2D(width, height, TextureFormat.RGBA32, false)
            {
                name = "Pixel Text 8x8",
                filterMode = FilterMode.Point,
                wrapMode = TextureWrapMode.Clamp
            };
            texture.SetPixels32(pixels);
            texture.Apply(false, true);
            return texture;
        }

        private static int LineWidth(string line) => Mathf.Max(0,
            line.Length * (GlyphWidth + LetterSpacing) - LetterSpacing);
    }
